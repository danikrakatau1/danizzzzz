const fs=require('fs');
const path=require('path');
const cp=require('child_process');
const root=process.cwd();
const publicDir=path.join(root,'public');
const htmlPath=path.join(publicDir,'index.html');
if(!fs.existsSync(htmlPath)) throw new Error('public/index.html not found — run existing ARSTORE build first');
const cssSrc=path.join(root,'ui-premium-618-v257.css');
const jsSrc=path.join(root,'ui-premium-618-v257.js');
for(const p of [cssSrc,jsSrc]) if(!fs.existsSync(p)) throw new Error('missing '+path.basename(p));
cp.execFileSync(process.execPath,['--check',jsSrc],{stdio:'inherit'});
const cssDst=path.join(publicDir,'css','ui-premium-618-v257.css');
const jsDst=path.join(publicDir,'js','ui-premium-618-v257.js');
fs.mkdirSync(path.dirname(cssDst),{recursive:true});fs.mkdirSync(path.dirname(jsDst),{recursive:true});
fs.copyFileSync(cssSrc,cssDst);fs.copyFileSync(jsSrc,jsDst);
let html=fs.readFileSync(htmlPath,'utf8');
const cssTag='<link rel="stylesheet" href="css/ui-premium-618-v257.css?v=257">';
const jsTag='<script src="js/ui-premium-618-v257.js?v=257"></script>';
if(!html.includes('ui-premium-618-v257.css')) html=html.replace('</head>',`  ${cssTag}\n</head>`);
if(!html.includes('ui-premium-618-v257.js')) html=html.replace('</body>',`  ${jsTag}\n</body>`);
fs.writeFileSync(htmlPath,html);
console.log('PREMIUM 618 V257 APPLIED — UI/UX only; master fee/profit/formula payload untouched');
